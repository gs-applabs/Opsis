"""Regenerate bundled sky profiles with Python/Pillow and Node.js."""
import json
from pathlib import Path
import subprocess

from PIL import Image

wallpaper = Path(__file__).resolve().parents[1] / "src/Widgets/wallpaper"
scenes = wallpaper / "scenes"
paths = {"scenes/acropolis.webp", "scenes/mountain-lake.webp"}
for catalog in ("capitals.json", "islands.json"):
    paths.update(scene["file"] for scene in json.loads((scenes / catalog).read_text()) if scene.get("file"))

width = 512
profiles = {}
for name in sorted(paths):
    with Image.open(wallpaper / name) as source:
        height = max(1, min(512, round(width * source.height / source.width)))
        pixels = source.convert("RGBA").resize((width, height), Image.Resampling.BILINEAR).tobytes()
    rows = json.loads(subprocess.check_output([
        "node", "-e",
        """
        const {skyline} = require(process.argv[1]);
        const pixels = require('node:fs').readFileSync(0);
        console.log(JSON.stringify([...skyline(pixels, +process.argv[2], +process.argv[3])]));
        """,
        str(wallpaper / "sky-mask.js"), str(width), str(height),
    ], input=pixels))
    profiles[name] = [height, rows] if sum(row > 0 for row in rows) >= width / 4 else None

(wallpaper / "scene-sky-profiles.js").write_text(
    "// Generated by tools/generate-weather-sky-masks.py.\n"
    + "window.OpsisSceneSkyProfiles = {\n"
    + ",\n".join(json.dumps(name) + ":" + json.dumps(profile, separators=(",", ":"))
                 for name, profile in profiles.items())
    + "\n};\n",
    encoding="utf-8",
)
